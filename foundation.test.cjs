const { readFileSync } = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const element = { value: '', classList: { add() {}, remove() {} }, getContext: () => ({}), addEventListener() {} };
const context = vm.createContext({ document: { querySelector: () => element, querySelectorAll: () => [] }, console, window: { clearTimeout() {}, setTimeout() {} } });
vm.runInContext(['foundation-details.js', 'roofs.js','roof-junctions.js','roof-trimming.js','roof-framing.js', 'rooms.js', 'stairs.js','stair-coordination.js','floor-openings.js','floor-cuts.js','stair-headroom.js','stair-rails.js','stair-rail-members.js','stair-rail-ends.js', 'deck-framing.js','deck-boards.js','deck-supports.js','deck-posts.js','deck-post-members.js','deck-edges.js','services.js','service-connections.js','service-envelopes.js','material-references.js','service-clearance-checks.js','service-route-body-checks.js','service-route-volumes.js'].map((path) => readFileSync(path, 'utf8')).join('\n') + '\n' + readFileSync('app.js', 'utf8').split('document.querySelectorAll("[data-tool]")')[0], context);
const run = (code) => vm.runInContext(code, context);
run('render = () => {}; scheduleSave = () => {};');
run('state.model = normalizeModel(createExampleModel());');
assert.equal(run('state.model.pads.length'), 55);
assert.equal(run('state.model.piers.length'), 55);
assert.equal(run('foundationConnectionIssues().length'), 0);
assert.equal(run('supportVolume(state.model.pads[0])'), 144000000);
assert.ok(Math.abs(run('supportVolume(state.model.piers[0]) / 1e9') - Math.PI * .15 ** 2 * 1.5) < 1e-12);
assert.equal(run('reinforcementIssues(state.model.piers[0], "pier").some(s => s.includes("do not meet"))'), false);
run('state.model.piers[0].elevation += 50;');
assert.equal(run('reinforcementIssues(state.model.piers[0], "pier").some(s => s.includes("do not meet"))'), true);
run('state.model.piers[0].center.x += 1000;');
assert.equal(run('reinforcementIssues(state.model.piers[0], "pier").some(s => s.includes("outside"))'), true);
run('state.model = normalizeModel(createExampleModel()); state.model.foundations=[{id:"foundation-test",levelId:state.model.activeLevelId,a:{x:0,y:0},b:{x:1000,y:0},width:450,depth:300,elevation:-600,role:"external",status:"preliminary"}]; state.model.foundations[0].a.x += 100;');
assert.ok(run('foundationConnectionIssues().length') > 0, '100mm gap cannot pass continuity');
run('state.model = normalizeModel(createExampleModel()); state.selected = { type: "pad", id: state.model.pads[0].id };');
run('updateSelectedField("width", "800");');
assert.equal(run('selectedObject().width'), 800);
run('undo();'); assert.equal(run('state.model.pads[0].width'), 600);
run('redo(); state.selected = { type: "pad", id: state.model.pads[0].id };');
assert.equal(run('selectedObject().width'), 800);
run('updateSelectedField("depth", "-10");'); assert.equal(run('selectedObject().depth'), 400);
run('updateSelectedField("rebar.mode", "reinforced"); addReinforcementRow(); updateSelectedField("bar.0.designation", "N12"); updateSelectedField("bar.0.count", "4"); updateSelectedField("bar.0.cutLength", "560");');
assert.equal(run('supportQuantityRows().find(r => r.unit === "m").net'), 2.24);
run('updateSelectedField("bar.0.count", "4.5");'); assert.equal(run('selectedObject().reinforcement.bars[0].count'), 4);
run('updateSelectedField("rebar.cover", "200");');
assert.equal(run('reinforcementIssues(selectedObject(), "pad").some(s => s.includes("no space"))'), true);
run('addReinforcementRow(); updateSelectedField("bar.1.designation", "SL72"); updateSelectedField("bar.1.count", "2");');
assert.equal(run('supportQuantityRows().find(r => r.label === "Scheduled mesh sheets").net'), 2);
run('state.model = normalizeModel(JSON.parse(JSON.stringify(state.model)));');
assert.equal(run('state.model.pads[0].reinforcement.bars[0].count'), 4);
run('let csvCapture = ""; download = (name, text) => { csvCapture = text; }; exportFoundationCsv();');
assert.ok(run('csvCapture.includes("N12") && csvCapture.includes("SL72") && csvCapture.includes("pad-house-1500-1500")'));
run('deleteSupport();');
assert.equal(run('state.model.pads.length'), 54);
assert.equal(run('state.model.piers[0].padId'), '');
run('undo();'); assert.equal(run('state.model.pads.length'), 55);
run('let legacy = createExampleModel(); delete legacy.pads; delete legacy.piers; state.model = normalizeModel(legacy);');
assert.equal(run('state.model.pads.length'), 0);
assert.throws(() => run('normalizeModel({ levels: [], walls: [], openings: [], decks: [] })'), /at least one level/);
console.log('Foundation tests passed: geometry, continuity, links, validation, quantities, legacy import, JSON round-trip, undo/redo, deletion and CSV.');
