const {readFileSync}=require('node:fs');
const vm=require('node:vm'),assert=require('node:assert/strict');
const elements=new Map();
const element=id=>{if(!elements.has(id))elements.set(id,{value:'',innerHTML:'',textContent:'',classList:{add(){},remove(){}},getContext:()=>({}),addEventListener(){}});return elements.get(id);};
const context=vm.createContext({document:{querySelector:element,querySelectorAll:()=>[]},console,window:{clearTimeout(){},setTimeout(){}}});
vm.runInContext(['foundation-details.js','roofs.js','roof-junctions.js','roof-trimming.js','roof-framing.js','rooms.js','stairs.js','stair-coordination.js','floor-openings.js','floor-cuts.js','stair-headroom.js','stair-rails.js','stair-rail-members.js','stair-rail-ends.js','deck-framing.js','deck-boards.js','deck-supports.js','deck-posts.js','deck-post-members.js','deck-edges.js','services.js','service-connections.js','service-envelopes.js','material-references.js','service-clearance-checks.js','service-route-body-checks.js','service-route-volumes.js'].map(p=>readFileSync(p,'utf8')).join('\n')+'\n'+readFileSync('app.js','utf8').split('document.querySelectorAll("[data-tool]")')[0],context);
const run=s=>vm.runInContext(s,context);
run('render=()=>{};scheduleSave=()=>{};state.model=createEmptyModel();state.visibility.serviceConnections=false;state.drawing={start:{x:0,y:0},current:{x:3000,y:4000}};commitService();updateSelectedField("endElevation","12000");');
assert.equal(run('serviceGeometry(selectedObject()).plan'),5000);
assert.equal(run('serviceGeometry(selectedObject()).length'),13000);
assert.equal(run('objectSpecificationMeasure("service",selectedObject()).quantity'),13);
run('updateSelectedField("system","electrical");');
assert.equal(run('serviceQuantityRows()[2].net'),13);
assert.equal(run('hitService({x:1500,y:2000}).type'),'service');
run('state.visibility["service-electrical"]=false;');
assert.equal(run('hitService({x:1500,y:2000})'),null);
assert.equal(run('serviceQuantityRows()[2].net'),13,'Hidden routes remain measured');
run('updateSelectedField("endX","0");updateSelectedField("endY","0");');
assert.equal(run('serviceGeometry(selectedObject()).length'),12000,'Vertical riser');
run('updateSelectedField("endElevation","0");');
assert.equal(run('selectedObject().points[1].z'),12000,'Zero length segment edit rejected');
run('updateSelectedField("startElevation","");');
assert.equal(run('selectedObject().points[0].z'),0,'Blank numeric edit rejected');

// Migration is lossless and does not mutate the original data.
run('let legacy=clone(state.model);let oldRoute=legacy.services[0];oldRoute.a={x:0,y:0};oldRoute.b={x:3000,y:4000};oldRoute.startElevation=-100;oldRoute.endElevation=11900;oldRoute.specificationId="saved-product";delete oldRoute.points;legacy.schema=10;let migrated=normalizeModel(legacy);');
assert.equal(run('migrated.schema'),30);
assert.equal(run('serviceGeometry(migrated.services[0]).length'),13000);
assert.equal(run('migrated.services[0].id===legacy.services[0].id'),true);
assert.equal(run('migrated.services[0].specificationId'),'saved-product');
assert.equal(run('legacy.services[0].points'),undefined);
assert.equal(run('migrated.services[0].a'),undefined,'Single canonical geometry');
assert.equal(run('normalizeModel(createExampleModel()).serviceItems.length'),0);

// Multi-leg length must sum per segment, not use the end-to-end chord or net rise.
run('let route=state.model.services[0];route.points=[{x:0,y:0,z:0},{x:3000,y:4000,z:12000},{x:3000,y:4000,z:9000},{x:9000,y:12000,z:9000}];validateService(route);');
assert.equal(run('serviceGeometry(route).length'),26000);
assert.equal(run('serviceGeometry(route).plan'),15000);
assert.equal(run('serviceGeometry(route).rise'),9000);
assert.equal(run('serviceGeometry(route).segments.length'),3);
assert.equal(run('hitService({x:6000,y:8000}).id'),run('route.id'));
run('serviceAction("service-insert-point",0);');
assert.equal(run('route.points.length'),5);
assert.equal(run('serviceGeometry(route).length'),26000,'Midpoint insertion preserves length');
run('serviceAction("service-remove-point",1);');
assert.equal(run('route.points.length'),4);
assert.equal(run('serviceGeometry(route).length'),26000);
run('serviceAction("service-append");');
assert.equal(run('route.points.length'),5);
assert.equal(run('serviceGeometry(route).length'),36000);
run('undo();redo();');
assert.equal(run('serviceGeometry(state.model.services[0]).length'),36000);
run('undo();state.selected={type:"service",id:state.model.services[0].id};updateSelectedField("point-1-z","13000");');
assert.equal(run('state.model.services[0].points[1].z'),13000);
run('undo();state.selected={type:"service",id:state.model.services[0].id};');
assert.equal(run('state.model.services[0].points[1].z'),12000);
assert.throws(()=>run('let bad=clone(state.model);bad.services[0].points[1]=clone(bad.services[0].points[0]);normalizeModel(bad);'));
assert.throws(()=>run('let badPoints=clone(state.model);badPoints.services[0].points=[];normalizeModel(badPoints);'));
assert.throws(()=>run('let badSize=clone(state.model);badSize.services[0].points=Array.from({length:501},(_,i)=>({x:i*10,y:0,z:0}));normalizeModel(badSize);'));
assert.throws(()=>run('let badZ=clone(state.model);badZ.services[0].points[1].z=null;normalizeModel(badZ);'));
assert.throws(()=>run('let badSystem=clone(state.model);badSystem.services[0].system="invalid";normalizeModel(badSystem);'));
assert.throws(()=>run('let badDup=clone(state.model);badDup.services.push(clone(badDup.services[0]));normalizeModel(badDup);'));
run('state.serviceDraft=[];addServicePoint({x:100,y:100});addServicePoint({x:1100,y:100});addServicePoint({x:1100,y:1100});let routeCount=state.model.services.length;finishServiceRoute();');
assert.equal(run('state.model.services.length'),run('routeCount+1'));
assert.equal(run('serviceGeometry(selectedObject()).length'),2000);
assert.equal(run('state.serviceDraft.length'),0);
run('addServicePoint({x:100,y:100});cancelDrawing();');
assert.equal(run('state.serviceDraft.length'),0);
assert.equal(run('state.model.services.length'),run('routeCount+1'),'Cancel does not commit');
run('state.selected={type:"service",id:state.model.services[1].id};serviceAction("service-remove-point",1);let prior=JSON.stringify(selectedObject().points);serviceAction("service-remove-point",1);');
assert.equal(run('JSON.stringify(selectedObject().points)'),run('prior'),'Cannot remove below two points');

// Explicit items, references, count schedules and product links.
run('placeServiceItem("fitting",{x:3000,y:4000});updateSelectedField("system","electrical");updateSelectedField("partType","Junction box");updateSelectedField("elevation","12000");updateSelectedField("routeId",state.model.services[0].id);let fittingId=selectedObject().id;');
